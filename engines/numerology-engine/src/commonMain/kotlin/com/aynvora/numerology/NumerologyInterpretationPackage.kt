    fun getInterpretation(rulesetId: String, subjectId: String): NumerologyInterpretation? {
        val item = ALL_INTERPRETATIONS[subjectId]
        return if (item?.rulesetId == rulesetId || item?.rulesetId == "UNIVERSAL") item else null
    }

    fun getByCalculation(
        rulesetId: String,
        type: NumerologyCalculationType,
        value: Int
    ): NumerologyInterpretation? {
        return ALL_INTERPRETATIONS.values.firstOrNull {
            (it.rulesetId == rulesetId || it.rulesetId == "UNIVERSAL") &&
                    it.calculationType == type &&
                    it.value == value
        }
    }

    fun getInterpretationsForRuleset(rulesetId: String): List<NumerologyInterpretation> {
        return ALL_INTERPRETATIONS.values.filter { it.rulesetId == rulesetId }
    }

    /**
     * Backward-compatible root finder for early consumer cards.
     */
    fun findRoot(number: Int): NumerologyInterpretation? {
        return ALL_INTERPRETATIONS["pythagorean_$number"]
            ?: ALL_INTERPRETATIONS["chaldean_$number"]
            ?: ALL_INTERPRETATIONS["indian_$number"]
    }

    /**
     * Authoritative resolver that maps a deterministic [NumerologyResult]
     * to a source-gated, ruleset-specific [NumerologyInterpretationBundle].
     */
    fun resolveInterpretations(result: NumerologyResult): NumerologyInterpretationBundle {
        val profile = result.profile
        val rulesetId = profile.rulesetId
        val ruleset = NumerologyRuleset.fromId(rulesetId) ?: NumerologyRuleset.CHALDEAN_CHEIRO_V1

        var primary: NumerologyInterpretation? = null
        val secondaries = mutableListOf<NumerologyInterpretation>()
        var noticeKey: String? = null

        when (ruleset.id) {
            NumerologyRuleset.PYTHAGOREAN_WESTERN_V1.id -> {
                val destinyVal = profile.destiny?.destinyValue ?: 1
                primary = ALL_INTERPRETATIONS["pythagorean_$destinyVal"]
                profile.radical?.radicalValue?.let { rad ->
                    if (rad != destinyVal) {
                        ALL_INTERPRETATIONS["pythagorean_$rad"]?.let { secondaries.add(it) }
                    }
                }
                noticeKey = "numerology.interp.notice.contemplative"
            }

            NumerologyRuleset.CHALDEAN_CHEIRO_V1.id -> {
                val radVal = profile.radical?.radicalValue ?: 1
                primary = ALL_INTERPRETATIONS["chaldean_$radVal"]
                profile.destiny?.destinyValue?.let { des ->
                    if (des != radVal) {
                        ALL_INTERPRETATIONS["chaldean_$des"]?.let { secondaries.add(it) }
                    }
                }
                // Compound number meanings if available
                profile.nameNumber?.nameValue?.let { nameVal ->
                    ALL_INTERPRETATIONS["chaldean_compound_$nameVal"]?.let { secondaries.add(it) }
                }
                noticeKey = "numerology.interp.notice.contemplative"
            }

            NumerologyRuleset.INDIAN_ANK_JYOTISH_V1.id -> {
                val moolank = profile.radical?.radicalValue ?: 1
                primary = ALL_INTERPRETATIONS["indian_$moolank"]
                profile.destiny?.destinyValue?.let { bhagyank ->
                    if (bhagyank != moolank) {
                        ALL_INTERPRETATIONS["indian_$bhagyank"]?.let { secondaries.add(it) }
                    }
                }
                ALL_INTERPRETATIONS["indian_rel_mitra"]?.let { secondaries.add(it) }
                noticeKey = "numerology.interp.notice.contemplative"
            }

            NumerologyRuleset.LO_SHU_CLASSICAL_V1.id -> {
                val grid: LoShuGrid? = result.loShuResult?.grid ?: profile.loShu
                val presentDigits = grid?.presentDigits ?: emptyList()
                val firstPresent = presentDigits.firstOrNull() ?: 1
                primary = ALL_INTERPRETATIONS["loshu_digit_$firstPresent"]
                // Arrows of strength
                grid?.arrows?.forEach { arrow ->
                    if (arrow.status == LoShuArrowStatus.ARROW_OF_STRENGTH) {
                        when (arrow.plane) {
                            LoShuPlaneType.DETERMINATION_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_determination"]?.let {
                                secondaries.add(
                                    it
                                )
                            }

                            LoShuPlaneType.COMPASSION_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_spirituality"]?.let {
                                secondaries.add(
                                    it
                                )
                            }

                            LoShuPlaneType.MIND_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_intellect"]?.let {
                                secondaries.add(
                                    it
                                )
                            }

                            LoShuPlaneType.PRACTICAL_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_practicality"]?.let {
                                secondaries.add(
                                    it
                                )
                            }

                            LoShuPlaneType.THOUGHT_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_planner"]?.let {
                                secondaries.add(
                                    it
                                )
                            }

                            LoShuPlaneType.WILL_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_willpower"]?.let {
                                secondaries.add(
                                    it
                                )
                            }

                            LoShuPlaneType.ACTION_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_activity"]?.let {
                                secondaries.add(
                                    it
                                )
                            }

                            LoShuPlaneType.SOUL_PLANE -> ALL_INTERPRETATIONS["loshu_arrow_str_balance"]?.let {
                                secondaries.add(
                                    it
                                )
                            }
                        }
                    }
                }
                noticeKey = "numerology.interp.notice.contemplative"
            }

            NumerologyRuleset.HEBREW_GEMATRIA_CLASSICAL_V1.id -> {
                primary = ALL_INTERPRETATIONS["gematria_ragil_equiv"]
                ALL_INTERPRETATIONS["gematria_letter_classes"]?.let { secondaries.add(it) }
                noticeKey = "numerology.interp.notice.alphanumeric"
            }

            NumerologyRuleset.HEBREW_MISPAR_GADOL_V1.id -> {
                primary = ALL_INTERPRETATIONS["gematria_gadol_sofit"]
                ALL_INTERPRETATIONS["gematria_letter_classes"]?.let { secondaries.add(it) }
                noticeKey = "numerology.interp.notice.alphanumeric"
            }

            NumerologyRuleset.ARABIC_ABJAD_MASHRIQI_V1.id -> {
                primary = ALL_INTERPRETATIONS["abjad_mashriqi_system"]
                noticeKey = "numerology.interp.notice.alphanumeric"
            }

            NumerologyRuleset.ARABIC_ABJAD_MAGHRIBI_V1.id -> {
                primary = ALL_INTERPRETATIONS["abjad_maghribi_system"]
                noticeKey = "numerology.interp.notice.alphanumeric"
            }

            NumerologyRuleset.AGRIPPAN_OCCULT_V1.id -> {
                val scale = profile.nameNumber?.nameValue ?: profile.radical?.radicalValue ?: 1
                primary = ALL_INTERPRETATIONS["agrippan_scale_$scale"]
                noticeKey = "numerology.interp.notice.contemplative"
            }

            NumerologyRuleset.INDIAN_KATAPAYADI_V1.id -> {
                primary = ALL_INTERPRETATIONS["katapayadi_mnemonic_system"]
                ALL_INTERPRETATIONS["katapayadi_reversal_rule"]?.let { secondaries.add(it) }
                noticeKey = "numerology.interp.notice.mnemonic"
            }

            NumerologyRuleset.CHINESE_NINE_STAR_KI_V1.id -> {
                val starNum = result.nineStarKiResult?.principalStar?.starNumber ?: 1
                primary = ALL_INTERPRETATIONS["ninestarki_$starNum"]
                noticeKey = "numerology.interp.notice.contemplative"
            }

            NumerologyRuleset.TAROT_BIRTH_CARD_V1.id -> {
                val cardNum = result.tarotBirthCardResult?.personalityCardNumber ?: 1
                primary = ALL_INTERPRETATIONS["tarot_card_$cardNum"]
                result.tarotBirthCardResult?.soulCardNumber?.let { soul ->
                    if (soul != cardNum) {
                        ALL_INTERPRETATIONS["tarot_card_$soul"]?.let { secondaries.add(it) }
                    }
                }
                if (cardNum == 19) {
                    ALL_INTERPRETATIONS["tarot_triad_19_10_1"]?.let { secondaries.add(it) }
                }
                noticeKey = "numerology.interp.notice.contemplative"
            }
        }

        return NumerologyInterpretationBundle(
            rulesetId = ruleset.id,
            traditionId = ruleset.name,
            contentVersion = CONTENT_VERSION,
            primaryInterpretation = primary,
            secondaryInterpretations = secondaries,
            ethicalDisclaimerKey = "numerology.disclaimer.body",
            historicalContextNoticeKey = noticeKey,
        )
    }
